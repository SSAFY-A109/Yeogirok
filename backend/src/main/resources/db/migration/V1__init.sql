        stay_minutes integer not null,
        travel_minutes_from_previous integer,
        visit_date date not null,
        arrival_at timestamp(6) with time zone,
        departure_at timestamp(6) with time zone,
        id bigint generated by default as identity,
        room_id bigint not null,
        room_place_id bigint not null,
        travel_data_as_of timestamp(6) with time zone,
        travel_data_source varchar(100),
        travel_unavailable_reason text,
        primary key (id),
        constraint uq_schedule_items_room_date_position unique (room_id, visit_date, position),
        constraint schedule_items_position_check check (position >= 1),
        constraint schedule_items_stay_minutes_check check (stay_minutes BETWEEN 1 AND 720),
        constraint schedule_items_travel_minutes_check check (travel_minutes_from_previous >= 0),
        constraint schedule_items_distance_check check (distance_from_previous_meters >= 0),
        constraint schedule_items_time_order_check check (arrival_at IS NULL OR departure_at IS NULL OR arrival_at <= departure_at)
    );

