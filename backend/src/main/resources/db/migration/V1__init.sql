-- V1: 처음 스키마.
--
-- Flyway 를 들이기 전까지 운영 DB 는 Hibernate(ddl-auto=update)가 엔티티를 보고 만들었다. 이 파일은 그때와 같은 모양을 그대로 옮긴 것이다
-- (2026-11-11, backend/dev 18ea256 의 엔티티로 Hibernate 가 만든 DDL). 열·제약·인덱스는 update 로 만든 DB 와 비교해 맞췄다.
-- 다른 점은 하나다. user_push_tokens 는 엔티티의 platform 열거형 검사와 이름 붙인 검사(user_push_tokens_platform_check)가
-- PostgreSQL 에서 같은 이름으로 겹쳐 update 로는 만들어지지 않았다. 여기서는 이름 붙인 검사 하나만 두고 만든다.
--
-- 노션 ERD DDL 에만 있는 것(FK 대부분, ENUM 타입, 열 기본값, 부분 인덱스, DEFERRABLE 유니크)은 넣지 않았다.
-- 코드로 검증한 적이 없어, 백엔드에서 합의한 뒤 다음 번호 파일로 추가한다(backend/docs/08-flyway.md).
--
-- 규칙: 한 번 적용된 파일은 고치지 않는다. 바꿀 것이 있으면 V2__설명.sql 처럼 새 번호 파일을 만든다.

-- 회원
create table users (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) with time zone not null,
        withdrawn_at timestamp(6) with time zone,
        nickname varchar(50) not null,
        email varchar(320),
        profile_image_url text,
        provider varchar(255) not null check ((provider in ('GOOGLE','KAKAO'))),
        provider_subject varchar(255) not null,
        status varchar(255) not null check ((status in ('ACTIVE','WITHDRAWN'))),
        primary key (id)
    );

-- Android 푸시 기기 토큰
