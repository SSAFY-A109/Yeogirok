        constraint travel_rooms_dates_check check ((start_date IS NULL AND end_date IS NULL) OR (start_date IS NOT NULL AND end_date IS NOT NULL AND start_date <= end_date)),
        constraint travel_rooms_version_check check (version >= 1)
    );

