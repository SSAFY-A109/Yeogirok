-- 장소
create table places (
        latitude numeric(10,7) not null,
        longitude numeric(10,7) not null,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        synced_at timestamp(6) with time zone,
        parking_status varchar(20) not null check ((parking_status in ('AVAILABLE','UNAVAILABLE','UNKNOWN'))),
        provider varchar(20) not null check ((provider in ('TOUR_API','MANUAL'))),
        region_code varchar(30),
        category_code varchar(50),
        provider_place_id varchar(100),
        region_name varchar(100),
        address text,
        description text,
        image_attribution text,
        image_url text,
        name varchar(255) not null,
        parking_info jsonb not null,
        primary key (id),
        constraint uk_places_provider_place unique (provider, provider_place_id),
        constraint places_name_check check (char_length(btrim(name)) > 0),
        constraint places_latitude_check check (latitude BETWEEN -90 AND 90),
        constraint places_longitude_check check (longitude BETWEEN -180 AND 180),
        constraint places_provider_place_id_check check ((provider = 'TOUR_API' AND provider_place_id IS NOT NULL) OR (provider = 'MANUAL' AND provider_place_id IS NULL))
    );

