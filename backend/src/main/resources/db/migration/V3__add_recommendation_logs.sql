-- V2: 추천 결과·담기 이력(recommendation_logs). 여행방 장소 추천(API-034)이 추천 한 번마다 REQUEST 행을 남기고,
-- 그 ID 가 recommendationRequestId 다. 엔티티는 domain/recommendation/entity/RecommendationLog.
--
-- 노션 ERD DDL 과 다른 점은 V1 과 같은 기준이다(backend/docs/08-flyway.md 4절).
-- ENUM 타입 대신 varchar + 허용값 검사, 열 기본값 없음, travel_rooms·users FK 없음(다른 테이블처럼 서비스가 확인한다).
-- 추천 조건(travel_rooms.preferences)은 V1 에 이미 있는 jsonb 열을 쓴다.

create table recommendation_logs (
        rank integer,
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        room_id bigint not null,
        user_id bigint not null,
        event_type varchar(20) not null check ((event_type in ('REQUEST','ADD','REMOVE'))),
        status varchar(20) not null check ((status in ('QUEUED','RUNNING','SUCCEEDED','FAILED'))),
        mode varchar(30) check ((mode in ('PERSONALIZED','REGIONAL_POPULAR','FALLBACK'))),
        place_key varchar(255),
        input_payload jsonb not null,
        place_snapshot jsonb not null,
        result_payload jsonb not null,
        primary key (id),
        constraint recommendation_logs_rank_check check (rank IS NULL OR rank >= 1),
        constraint recommendation_logs_event_check check ((event_type = 'REQUEST' AND place_key IS NULL AND mode IS NOT NULL) OR (event_type <> 'REQUEST' AND place_key IS NOT NULL))
    );

-- 방별 추천 기록 조회(재전송은 ID 로 찾지만, 방 단위 정리·분석에 쓴다).
create index ix_recommendation_logs_room on recommendation_logs (room_id, id);
