export function recordError(error: unknown, fallback = "요청을 처리하지 못했어요. 다시 확인해 주세요.") {
  if (!isApiError(error)) {
    return fallback;
  }

  if (error.status === 0) {
    return "서버 응답을 확인하지 못했어요. 최신 기록을 확인한 뒤 다시 시도해 주세요.";
  }

  if (error.status === 403) {
    return messages[error.code] ?? "이 기록에 접근할 권한이 없어요.";
  }

  return messages[error.code] ?? fallback;
}
